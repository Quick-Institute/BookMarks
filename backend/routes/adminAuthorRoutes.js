import express from "express";
import multer from "multer";
import path from "node:path";
import fs from "node:fs";
import {randomUUID} from "node:crypto";
import {requireAuth} from "../middleware/authMiddleware.js";
import {requireAdmin} from "../middleware/adminMiddleware.js";
import {index,show,create,update,remove,uploadPhoto} from "../controllers/adminAuthorController.js";
const router=express.Router();
const directory=path.resolve("uploads","author-photos");
fs.mkdirSync(directory,{recursive:true});
const upload=multer({storage:multer.diskStorage({destination:(_req,_file,cb)=>cb(null,directory),filename:(_req,file,cb)=>cb(null,`${randomUUID()}${{"image/jpeg":".jpg","image/png":".png","image/webp":".webp"}[file.mimetype]}`)}),limits:{fileSize:5*1024*1024},fileFilter:(_req,file,cb)=>cb(null,["image/jpeg","image/png","image/webp"].includes(file.mimetype))});
const photo=(req,res,next)=>upload.single("photo")(req,res,err=>err?res.status(400).json({message:err.code==="LIMIT_FILE_SIZE"?"Photo must be 5 MB or smaller.":err.message}):next());
router.use(requireAuth,requireAdmin);
router.get("/",index);
router.post("/",create);
router.get("/:id",show);
router.put("/:id",update);
router.post("/:id/photo",photo,uploadPhoto);
router.delete("/:id",remove);
export default router;
